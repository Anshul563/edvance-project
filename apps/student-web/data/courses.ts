import type { Course, Level } from "@/types"
import { buildSections, totalDuration } from "./curriculum"

interface CourseSeed {
  id: string
  slug: string
  title: string
  subtitle: string
  description: string
  instructorId: string
  categorySlug: string
  level: Level
  rating: number
  reviewCount: number
  studentCount: number
  price: number
  discountPrice?: number
  language?: string
  publishedAt: string
  lastUpdated: string
  learningOutcomes: string[]
  prerequisites: string[]
  targetAudience: string[]
  bestseller?: boolean
  withCapstone?: boolean
}

function course(seed: CourseSeed): Course {
  const sections = buildSections(seed.categorySlug, seed.id, {
    withCapstone: seed.withCapstone,
  })
  return {
    ...seed,
    language: seed.language ?? "English",
    thumbnail: `/thumbnails/${seed.categorySlug}.svg`,
    sections,
    duration: totalDuration(sections),
  }
}

